export const TAG36H11_MAX_ID = CODES.length - 1; // 586

/** Lưới 10×10 (true = ô trắng, false = ô đen), gồm viền trắng ngoài + viền đen 1 ô + dữ liệu 6×6. */
export function tag36h11Grid(tagId: number): boolean[][] {
  if (!Number.isInteger(tagId) || tagId < 0 || tagId > TAG36H11_MAX_ID) {
    throw new Error(`tag_id ${tagId} ngoài phạm vi họ AprilTag 36h11 (0–${TAG36H11_MAX_ID})`);
  }
  const code = CODES[tagId];
  const grid: boolean[][] = Array.from({ length: TOTAL_WIDTH }, () => new Array(TOTAL_WIDTH).fill(false));
  for (let i = 0; i < TOTAL_WIDTH; i++) {
    grid[0][i] = true; grid[TOTAL_WIDTH - 1][i] = true;
    grid[i][0] = true; grid[i][TOTAL_WIDTH - 1] = true;
  }
  for (let i = 0; i < NBITS; i++) {
    if ((code >> BigInt(NBITS - i - 1)) & 1n) grid[BIT_Y[i] + BORDER_START][BIT_X[i] + BORDER_START] = true;
  }
  return grid;
}

/** SVG của một tag, cạnh khối 8×8 viền đen = `sizeMm` (đúng quy ước `tag_size_m`/`tag.sizes`);
 *  vẽ thêm 1 ô viền trắng mỗi bên để dễ cắt, không tính vào `sizeMm`. */
export function tag36h11Svg(tagId: number, sizeMm: number): string {
  const grid = tag36h11Grid(tagId);
  const cell = sizeMm / WIDTH_AT_BORDER;
  const svgSize = sizeMm + 2 * cell;
  let rects = "";
  for (let y = 0; y < TOTAL_WIDTH; y++) {
    for (let x = 0; x < TOTAL_WIDTH; x++) {
      if (!grid[y][x]) rects += `<rect x="${x * cell}" y="${y * cell}" width="${cell}" height="${cell}"/>`;
    }
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${svgSize}mm" height="${svgSize}mm" viewBox="0 0 ${svgSize} ${svgSize}">` +
    `<rect width="${svgSize}" height="${svgSize}" fill="#fff"/><g fill="#000">${rects}</g></svg>`;
}
